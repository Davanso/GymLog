export function translateTaxonomy(value: string) {
  return taxonomy[value.toUpperCase()] || translateExerciseName(value);
}

export function translateExerciseName(value: string) {
  let result = value;
  for (const [pattern, translation] of phrases) result = result.replace(pattern, translation);
  result = result
    .replace(/\s+/g, ' ')
    .replace(/\s+-\s+/g, ' — ')
    .trim();
  return result.charAt(0).toUpperCase() + result.slice(1);
}

